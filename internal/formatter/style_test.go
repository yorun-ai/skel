func TestSourceCanonicalStyle(t *testing.T) {
	cases := []struct{ name, source, want string }{
		{"field groups", `data User { id: uuid

@desc("Display name") name: string }`, `data User {
    id: uuid

    @desc("Display name")
    name: string
}`},
		{"permission comments", `resource User { action read action write }
actor ClientActor {}
api service UserApiService { for ClientActor auth required require any(User:read, /* keep */ User:write,
User:read) method get {} }`, `resource User {
    action read
    action write
}

actor ClientActor {}

api service UserApiService {
    for ClientActor
    auth required
    require any(
        User:read, /* keep */
        User:write,
        User:read
    )

    method get {}
}`},

		{"decorators", `@desc("用户")

pub data User { @desc("姓名") @example("张三")

name: string }`, `@desc("用户")
pub data User {
    @desc("姓名")
    @example("张三")
    name: string
}`},
		{"leading comments", `data A {} // trailing A
// B description
@desc("B") data B {}
/* C description */
data C {}`, `data A {} // trailing A

// B description
@desc("B")
data B {}

/* C description */
data C {}`},
		{"member comments", `pub service UserService {
// first
method first {} // trailing first
// second
@desc("Second") method second {}
}`, `pub service UserService {
    // first
    method first {} // trailing first

    // second
    @desc("Second")
    method second {}
}`},
		{"parenthesis edges", "@desc(\n\n\"User\"\n\n) data User {}", "@desc(\n    \"User\"\n)\ndata User {}"},
		{"nested permissions", `resource User { action read action write }
actor ClientActor {}
api service UserApiService { for ClientActor auth required require all(User:read, any(User:read,
User:write)) method first {} method second {} }`, `resource User {
    action read
    action write
}

actor ClientActor {}

api service UserApiService {
    for ClientActor
    auth required
    require all(
        User:read,
        any(
            User:read,
            User:write
        )
    )

    method first {}

    method second {}
}`},
		{"short audiences", `actor AActor {} actor BActor {}
api service UserApiService { for AActor,
BActor auth required method get {} }`, `actor AActor {}

actor BActor {}

api service UserApiService {
    for AActor, BActor
    auth required

    method get {}
}`},
		{"commented audiences", `actor AActor {} actor BActor {}
api service UserApiService { for AActor, // first caller
// second caller
BActor auth required method get {} }`, `actor AActor {}

actor BActor {}

api service UserApiService {
    for AActor, // first caller
        // second caller
        BActor
    auth required

    method get {}
}`},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			source := []byte("domain demo\n" + tc.source + "\n")
			want := "domain demo\n\n" + tc.want + "\n"
			got, err := ValidatedSource(source)
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != want {
				t.Fatalf("got:\n%s\nwant:\n%s", got, want)
			}
			if second := formatTestSource(t, got); string(second) != want {
				t.Fatalf("not idempotent:\n%s", second)
			}
			if parseDomainHash(t, "before.skel", source) != parseDomainHash(t, "after.skel", got) {
				t.Fatal("format changed semantic hash")
			}
		})
	}
}

func TestSourceFileHeaderAndWhitespace(t *testing.T) {
	cases := []struct{ name, source, want string }{
		{"copyright and license", "\n \t\n// Copyright Yorun\n// SPDX-License-Identifier: Apache-2.0\n@desc(\"用户领域\")\n\ndomain demo\nimport common.types\nimport common.auth\ndata User {}\n\n", "// Copyright Yorun\n// SPDX-License-Identifier: Apache-2.0\n\n@desc(\"用户领域\")\ndomain demo\n\nimport common.types\nimport common.auth\n\ndata User {}\n"},
		{"block header", "/*\n * Copyright Yorun\n * SPDX-License-Identifier: Apache-2.0\n */\ndomain demo", "/*\n * Copyright Yorun\n * SPDX-License-Identifier: Apache-2.0\n */\n\ndomain demo\n"},
		{"generated header", "// Code generated by skelc. DO NOT EDIT.\ndomain demo", "// Code generated by skelc. DO NOT EDIT.\n\ndomain demo\n"},
		{"header without domain", "// SPDX-License-Identifier: Apache-2.0\ndata User {}", "// SPDX-License-Identifier: Apache-2.0\n\ndata User {}\n"},
		{"separate domain explanation", "// Copyright Yorun\n\n\n// 用户领域\n@desc(\"用户\") domain demo", "// Copyright Yorun\n\n// 用户领域\n@desc(\"用户\")\ndomain demo\n"},
		{"ordinary attached comment", "// 用户领域\n@desc(\"用户\") domain demo", "// 用户领域\n@desc(\"用户\")\ndomain demo\n"},
		{"ordinary detached comment", "// File overview\n\n\n@desc(\"用户\") domain demo", "// File overview\n\n@desc(\"用户\")\ndomain demo\n"},
		{"comment paragraphs", "// File overview\n// First paragraph\n \t\n\n// Second paragraph\ndomain demo", "// File overview\n// First paragraph\n\n// Second paragraph\ndomain demo\n"},
		{"import groups", "domain demo\n\n\n// Core\nimport common.types\nimport common.auth\n \t\n\n// Extras\nimport extra.types\n\n\n// Models\ndata User {}", "domain demo\n\n// Core\nimport common.types\nimport common.auth\n\n// Extras\nimport extra.types\n\n// Models\ndata User {}\n"},
		{"blank lines and trailing spaces", "\n \t\n\ndomain demo  \n\n\n\ndata User {\n\nname: string \t\n \t\n\n\nage: int\n\n}\n\n \t\n", "domain demo\n\ndata User {\n    name: string\n\n    age: int\n}\n"},
		{"string and comment content", "// Copyright Yorun\n// keep  these   spaces\ndomain demo\ndata User { @desc(\"keep  these   spaces\") name: string }", "// Copyright Yorun\n// keep  these   spaces\n\ndomain demo\n\ndata User {\n    @desc(\"keep  these   spaces\")\n    name: string\n}\n"},
		{"comment only", "\n// Copyright Yorun\n\n\n", "// Copyright Yorun\n"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			for _, newline := range []string{"\n", "\r\n"} {
				source := []byte(strings.ReplaceAll(tc.source, "\n", newline))
				got, err := ValidatedSource(source)
				if err != nil {
					t.Fatal(err)
				}
				if string(got) != tc.want {
					t.Fatalf("got:\n%q\nwant:\n%q", got, tc.want)
				}
				if second := formatTestSource(t, got); string(second) != tc.want {
					t.Fatalf("not idempotent:\n%s", second)
				}
				// Whitespace changes must preserve every comment and string token.
				before, err := lex([]byte(tc.source))
				if err != nil {
					t.Fatal(err)
				}
				after, err := lex(got)
				if err != nil {
					t.Fatal(err)
				}
				values := func(tokens []_Token) []string {
					result := []string{}
					for _, token := range tokens {
						if token.kind != "Newline" {
							result = append(result, token.kind+":"+token.value)
						}
					}
					return result
				}
				if !reflect.DeepEqual(values(before), values(after)) {
					t.Fatal("format changed source tokens")
				}
			}
		})
	}
}
